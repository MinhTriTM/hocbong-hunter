const I18N = {
  LANG_LS: "hbh_selected_lang",
  currentLang: "vi",

  getLanguages() {
    return LANGUAGES_50;
  },

  getCurrentLangMeta() {
    return LANGUAGES_50.find(l => l.code === this.currentLang) || LANGUAGES_50[0];
  },

  getDict(langCode) {
    if (CORE_TRANSLATIONS[langCode]) return CORE_TRANSLATIONS[langCode];
    const base = CORE_TRANSLATIONS.en;
    const custom = NATIVE_TITLES_40[langCode] || {};
    return { ...base, ...custom };
  },

  t(key) {
    const dict = this.getDict(this.currentLang);
    return dict[key] || CORE_TRANSLATIONS.vi[key] || key;
  },

  /**
   * Trả về chỉ thị ngôn ngữ để nhúng vào Prompt của tất cả 10 Agent AI,
   * đảm bảo kết quả phân tích, lý do chấm điểm và dàn ý Motivation Letter
   * được trình bày đúng bằng ngôn ngữ người dùng đã chọn trong 50 ngôn ngữ!
   */
  getAgentLanguageInstruction() {
    const meta = this.getCurrentLangMeta();
    if (meta.code === "vi") {
      return "Ngôn ngữ phản hồi: Tiếng Việt chuẩn xác, rõ ràng.";
    }
    return `IMPORTANT LANGUAGE REQUIREMENT: The user has selected the language "${meta.name} (${meta.native})" [ISO code: ${meta.code}]. You MUST write all explanations, summaries, reasons, conditions, and guidance in ${meta.name} (${meta.native}).`;
  },

  setLanguage(langCode) {
    const meta = LANGUAGES_50.find(l => l.code === langCode) || LANGUAGES_50[0];
    this.currentLang = meta.code;
    try {
      localStorage.setItem(this.LANG_LS, meta.code);
    } catch { /* ignore */ }

    if (typeof document !== "undefined") {
      document.documentElement.lang = meta.code;
      document.documentElement.dir = meta.dir || "ltr";

      document.querySelectorAll("[data-i18n]").forEach(el => {
        const k = el.getAttribute("data-i18n");
        const val = this.t(k);
        if (val) el.textContent = val;
      });

      document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
        const k = el.getAttribute("data-i18n-placeholder");
        const val = this.t(k);
        if (val) el.setAttribute("placeholder", val);
      });
    }
  },

  init() {
    let saved = "vi";
    try {
      saved = localStorage.getItem(this.LANG_LS) || "vi";
    } catch { /* ignore */ }
    this.setLanguage(saved);
  },
};
